import { Document, Packer, Paragraph, TextRun } from 'docx'
import { saveAs } from 'file-saver'

export async function exportDocPro(cleanedText: string, username?: string) {
  if (!cleanedText) return

  const lines = cleanedText.split('\n\n').filter(Boolean)

  const paragraphs = lines.map(line => {
    const parts = line.split('**')
    const runs = parts.map((part, i) =>
      new TextRun({ text: part.trim(), bold: i % 2 !== 0 })
    )

    return new Paragraph({
      children: runs,
      spacing: { after: 200 },
    })
  })

  paragraphs.push(
    new Paragraph({
      children: [
        new TextRun({
          text: `Generated by CleanDoc Pro${username ? ` — ${username}` : ''}`,
          italics: true,
          color: '555555',
          size: 18,
        }),
      ],
      spacing: { before: 400 },
    })
  )

  const doc = new Document({ sections: [{ children: paragraphs }] })
  const blob = await Packer.toBlob(doc)
  saveAs(blob, 'CleanDoc_Pro.docx')
}