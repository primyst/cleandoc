import { Document, Packer, Paragraph, TextRun, HeadingLevel, Numbering } from 'docx'
import { saveAs } from 'file-saver'

export async function exportDocPro(cleanedText: string) {
  if (!cleanedText) return

  const lines = cleanedText.split('\n\n').filter(Boolean)

  const paragraphs = lines.map(line => {
    // Detect bullet points
    if (line.startsWith('-')) {
      const content = line.replace(/^-+\s*/, '')
      return new Paragraph({
        text: content,
        bullet: { level: 0 },
        spacing: { after: 200 },
      })
    }

    // Detect headers (lines starting with capital letters + short)
    const isHeader =
      /^[A-Z0-9 ,.'"()_-]+$/.test(line.trim()) && line.split(' ').length <= 6

    const parts = line.split('**')
    const runs = parts.map((part, i) =>
      new TextRun({ text: part.trim(), bold: i % 2 !== 0 })
    )

    if (isHeader) {
      return new Paragraph({
        children: runs,
        heading: HeadingLevel.HEADING_2,
        spacing: { after: 300, before: 300 },
      })
    }

    return new Paragraph({
      children: runs,
      spacing: { after: 200 },
    })
  })

  // Optional: Add closing note
  paragraphs.push(
    new Paragraph({
      children: [
        new TextRun({
          text: 'Generated by CleanDoc Pro',
          italics: true,
          color: '555555',
          size: 18,
        }),
      ],
      spacing: { before: 400 },
    })
  )

  const doc = new Document({ sections: [{ children: paragraphs }] })
  const blob = await Packer.toBlob(doc)
  saveAs(blob, 'CleanDoc_Pro.docx')
}